#!/usr/bin/env python3
"""Wraps tools/webui.html into src/webui.cpp (PROGMEM raw string). Run after editing the HTML:
    python3 tools/gen_webui.py
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(os.path.join(ROOT, "tools", "webui.html"), encoding="utf-8").read()
assert ')HTMLRAW"' not in html
out = ('// AUTO-GENERATED by tools/gen_webui.py from tools/webui.html - do not edit by hand\n'
       '#include "webui.h"\n\n'
       'const char INDEX_HTML[] PROGMEM = R"HTMLRAW(' + html + ')HTMLRAW";\n')
open(os.path.join(ROOT, "src", "webui.cpp"), "w", encoding="utf-8").write(out)
print("webui.cpp written (%d bytes of HTML)" % len(html.encode()))
